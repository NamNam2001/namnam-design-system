// ---------------------------------------------------------------- loading

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (err) {
    throw new Error(`cannot read ${file}: ${err.message}`);
  }
}

/** Flatten a DTCG tree into Map<id, token>. Group-level $type is inherited. */
function flatten(node, layer, out, prefix = [], inheritedType = undefined) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || child === null || typeof child !== 'object') continue;
    const path = [...prefix, key];
    const type = child.$type ?? inheritedType;
    if ('$value' in child) {
      const id = path.join('.');
      if (out.has(id)) throw new Error(`duplicate token "${id}" (layer ${layer})`);
      out.set(id, { id, type, value: child.$value, ext: child.$extensions, layer, description: child.$description });
    } else {
      flatten(child, layer, out, path, type);
    }
  }
  return out;
}

function loadSet(theme, platform) {
  const map = new Map();
  flatten(readJson(tokensPath('primitive.json')), 'primitive', map);
  flatten(readJson(tokensPath('base.json')), 'semantic', map);
  flatten(readJson(tokensPath('semantic', `${theme}.json`)), 'semantic', map);
  flatten(readJson(tokensPath('modes', `${platform}.json`)), 'semantic', map);
  const componentFiles = readdirSync(tokensPath('component')).filter((f) => f.endsWith('.json')).sort();
  for (const file of componentFiles) flatten(readJson(tokensPath('component', file)), 'component', map);
  return map;
}

/** Follow {alias} chains to a concrete value. Type/extensions fall back to the target's. */
function resolve(map, id, chain = []) {
  const token = map.get(id);
  if (!token) {
    const from = chain.length ? ` (referenced by "${chain[chain.length - 1]}")` : '';
    throw new Error(`unknown token {${id}}${from}`);
  }
  if (chain.includes(id)) throw new Error(`circular reference: ${[...chain, id].join(' -> ')}`);
  const match = typeof token.value === 'string' ? token.value.match(ALIAS) : null;
  if (!match) {
    if (!token.type) throw new Error(`token "${id}" has no $type`);
    return { type: token.type, value: token.value, ext: token.ext };
  }
  const target = resolve(map, match[1], [...chain, id]);
  return { type: token.type ?? target.type, value: target.value, ext: token.ext ?? target.ext };
}

/** All exported (non-primitive) tokens for one theme x platform, fully resolved. */
function resolvedSet(theme, platform) {
  const map = loadSet(theme, platform);
  const out = [];
  for (const token of map.values()) {
    if (token.layer === 'primitive') continue;
    out.push({ id: token.id, layer: token.layer, ...resolve(map, token.id) });
  }
  return out;
}

// ---------------------------------------------------------------- naming

const publicName = (id) => id.replace(/^component\./, '');
const cssVarName = (id) => `--${SYSTEM.css}-${publicName(id).replaceAll('.', '-')}`;
const cMacroName = (id) => `${SYSTEM.c}_TK_${publicName(id).replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase()}`;
const headerName = (theme, suffix) => `${SYSTEM.file}_theme_${theme}_${suffix}.h`;
// "embedded-4.3in" -> "4_3in": safe in file names and C identifiers.
const suffixOf = (platform) => platform.replace(/^embedded-/, '').replace(/[^a-zA-Z0-9]+/g, '_');

// ---------------------------------------------------------------- value helpers

function hexToRgb(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(String(hex));
  if (!m) throw new Error(`expected #RRGGBB color, got "${hex}"`);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function px(value) {
  const m = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value));
  if (!m) throw new Error(`expected a px dimension, got "${value}"`);
  return Math.round(Number(m[1]));
}

function ms(value) {
  const m = /^(\d+(?:\.\d+)?)(ms|s)$/.exec(String(value));
  if (!m) throw new Error(`expected a duration in ms/s, got "${value}"`);
  return Math.round(Number(m[1]) * (m[2] === 's' ? 1000 : 1));
}

const toHex = (n, width) => `0x${n.toString(16).toUpperCase().padStart(width, '0')}`;
const rgb565 = ([r, g, b]) => ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
const fontList = (v) => (Array.isArray(v) ? v : [v]);

function cssValue({ type, value }) {
  switch (type) {
    case 'color':
    case 'dimension':
    case 'duration':
    case 'number':
    case 'fontWeight':
      return String(value);
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'fontFamily':
      return fontList(value)
        .map((f) => (/^[a-z-]+$/i.test(f) ? f : `"${f}"`))
        .join(', ');
    default:
      throw new Error(`unsupported $type "${type}"`);
  }
}

function cLines(token) {
  const name = cMacroName(token.id);
  switch (token.type) {
    case 'color': {
      const rgb = hexToRgb(token.value);
      const rgb888 = (rgb[0] << 16) | (rgb[1] << 8) | rgb[2];
      return [
        `#define ${name} ${toHex(rgb888, 6)} /* ${token.value}; use lv_color_hex(${name}) */`,
        `#define ${name}_565 ${toHex(rgb565(rgb), 4)}`,
      ];
    }
    case 'dimension': {
      const v = px(token.value);
      const isPill = /(^|\.)radius(\.|$)/.test(token.id) && v >= 999;
      return [`#define ${name} ${isPill ? 'LV_RADIUS_CIRCLE' : v}`];
    }
    case 'duration':
      return [`#define ${name} ${ms(token.value)} /* ms */`];
    case 'number':
      return /opacity/.test(token.id)
        ? [`#define ${name} ${Math.round(token.value * 255)} /* lv_opa_t, ${token.value} */`]
        : [`#define ${name} ${token.value}`];
    case 'fontWeight':
      return [`#define ${name} ${token.value}`];
    case 'fontFamily':
      return [`#define ${name} "${fontList(token.value)[0]}" /* LVGL needs a font converted with lv_font_conv */`];
    case 'cubicBezier': {
      const path = token.ext?.lvgl?.path;
      const web = `cubic-bezier(${token.value.join(', ')})`;
      return path
        ? [`#define ${name} ${path} /* web: ${web} */`]
        : [`/* ${name}: ${web}, no LVGL path mapped (add $extensions.lvgl.path) */`];
    }
    default:
      throw new Error(`unsupported $type "${token.type}" for C output`);
  }
}

// ---------------------------------------------------------------- contrast

function luminance([r, g, b]) {
  const ch = (c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b);
}

function contrastRatio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const blend = (fg, bg, alpha) => fg.map((c, i) => Math.round(c * alpha + bg[i] * (1 - alpha)));

function runAudit(theme) {
  const byId = new Map(resolvedSet(theme, EMBEDDED_PLATFORMS[0] ?? PLATFORMS[0]).map((t) => [t.id, t]));
  const get = (id) => {
    const t = byId.get(id);
    if (!t) throw new Error(`audit references unknown token "${id}"`);
    return t;
  };
  return AUDIT.map((check) => {
    let bg = hexToRgb(get(check.bg).value);
    if (check.layer) bg = blend(hexToRgb(get(check.layer).value), bg, Number(get(check.layerAlpha).value));
    let fg = hexToRgb(get(check.fg).value);
    if (check.alpha) fg = blend(fg, bg, Number(get(check.alpha).value));
    const ratio = contrastRatio(fg, bg);
    return { ...check, theme, ratio: Math.round(ratio * 100) / 100, pass: ratio >= check.min };
  });
}

// ---------------------------------------------------------------- writers

function write(file, content) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, 'utf8');
}

function buildCss(combos) {
  const blocks = [`/* ${GENERATED_NOTE} */`];
  for (const theme of THEMES) {
    for (const platform of PLATFORMS) {
      const selectors = [`:root[data-theme="${theme}"][data-platform="${platform}"]`];
      const fallbackTheme = theme === CSS_FALLBACK.theme;
      const fallbackPlatform = platform === CSS_FALLBACK.platform;
      if (fallbackPlatform) selectors.push(`:root[data-theme="${theme}"]:not([data-platform])`);
      if (fallbackTheme) selectors.push(`:root[data-platform="${platform}"]:not([data-theme])`);
      if (fallbackTheme && fallbackPlatform) selectors.push(':root:not([data-theme]):not([data-platform])');
      const lines = combos[`${theme}/${platform}`].map((t) => `  ${cssVarName(t.id)}: ${cssValue(t)};`);
      blocks.push(`${selectors.join(',\n')} {\n  color-scheme: ${theme};\n${lines.join('\n')}\n}`);
    }
  }
  return `${blocks.join('\n\n')}\n`;
}

function buildJs(combos, audit) {
  const data = { system: SYSTEM, themes: THEMES, platforms: PLATFORMS, defaults: DEFAULT, combos: {}, audit };
  for (const [key, tokens] of Object.entries(combos)) {
    data.combos[key] = Object.fromEntries(
      tokens.map((t) => [publicName(t.id), { type: t.type, layer: t.layer, css: cssValue(t), cssVar: cssVarName(t.id), c: cMacroName(t.id) }]),
    );
  }
  return `/* ${GENERATED_NOTE} */\nwindow.DS_TOKENS = ${JSON.stringify(data, null, 2)};\n`;
}

function buildHeader(theme, platform, tokens) {
  const guard = `${SYSTEM.c}_THEME_${theme}_${platform}`.replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase();
  const out = [
    `/* ${GENERATED_NOTE}`,
    ` * ${SYSTEM.name} design tokens. Theme: ${theme}   Platform: ${platform}`,
    ` * Colors: lv_color_hex(${SYSTEM.c}_TK_X) for RGB888 panels, ${SYSTEM.c}_TK_X_565 for RGB565.`,
    ' * Opacity tokens are lv_opa_t (0-255). Motion paths are lv_anim path callbacks.',
    ' * These are macros only: include "lvgl.h" before using LV_RADIUS_CIRCLE / lv_anim_path_* tokens.',
    ' */',
    `#ifndef ${guard}_H`,
    `#define ${guard}_H`,
    '',
  ];
  let group = '';
  for (const token of tokens) {
    const top = publicName(token.id).split('.')[0];
    if (top !== group) {
      group = top;
      out.push('', `/* ---- ${top} ---- */`);
    }
    out.push(...cLines(token));
  }
  out.push('', `#endif /* ${guard}_H */`, '');
  return out.join('\n');
}

function buildSelectorHeader() {
  const lines = [
    `/* ${GENERATED_NOTE}`,
    ` * ${SYSTEM.name} theme selector. Include this file. Define ${SYSTEM.c}_THEME_LIGHT for the light theme;`,
    ` * define ${SYSTEM.c}_PLATFORM_<X> to pick a panel (the first embedded platform is the default). */`,
    `#ifndef ${SYSTEM.c}_THEME_H`,
    `#define ${SYSTEM.c}_THEME_H`,
    '',
  ];
  const includeBlock = (suffix) => [
    `#  if defined(${SYSTEM.c}_THEME_LIGHT)`,
    `#    include "${headerName('light', suffix)}"`,
    '#  else',
    `#    include "${headerName('dark', suffix)}"`,
    '#  endif',
  ];
  EMBEDDED_PLATFORMS.forEach((platform, i) => {
    const suffix = suffixOf(platform);
    const macro = `${SYSTEM.c}_PLATFORM_${suffix.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}`;
    lines.push(`${i === 0 ? '#if' : '#elif'} defined(${macro})`, ...includeBlock(suffix));
  });
  lines.push('#else /* default: first embedded platform */', ...includeBlock(suffixOf(EMBEDDED_PLATFORMS[0])));
  lines.push('#endif', '', `#endif /* ${SYSTEM.c}_THEME_H */`, '');
  return lines.join('\n');
}

function buildAuditMd(audit) {
  const rows = audit.map(
    (r) => `| ${r.theme} | ${r.kind} | \`${r.fg}\`${r.alpha ? ` @ \`${r.alpha}\`` : ''} | \`${r.bg}\`${r.layer ? ` + \`${r.layer}\` @ \`${r.layerAlpha}\`` : ''} | ${r.ratio.toFixed(2)} | ${r.min} | ${r.pass ? 'PASS' : '**FAIL**'} |`,
  );
  const failed = audit.filter((r) => !r.pass).length;
  return [
    `<!-- ${GENERATED_NOTE} -->`,
    '# Contrast audit',
    '',
    `${audit.length - failed}/${audit.length} checks pass. Thresholds: text 4.5:1, UI and disabled 3:1 (WCAG 2.2 AA, playbook §5).`,
    '',
    '| Theme | Kind | Foreground | Background | Ratio | Min | Result |',
    '|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- main

/** Every theme file and every platform mode file must define the same token names (playbook §16.15). */
function assertSameNames(kind, names, fileOf) {
  const sets = names.map((n) => [n, new Set(flatten(readJson(fileOf(n)), kind, new Map()).keys())]);
  const [firstName, first] = sets[0];
  for (const [name, set] of sets.slice(1)) {
    const missing = [...first].filter((id) => !set.has(id));
    const extra = [...set].filter((id) => !first.has(id));
    if (missing.length || extra.length) {
      throw new Error(`${kind} "${name}" and "${firstName}" define different tokens` +
        `${missing.length ? `; missing in ${name}: ${missing.join(', ')}` : ''}${extra.length ? `; only in ${name}: ${extra.join(', ')}` : ''}`);
    }
  }
}

/** Two token ids must never collapse to the same exported name (e.g. a.b-c vs a.b.c). */
function assertUniqueOutputNames(tokens) {
  for (const nameOf of [cssVarName, cMacroName]) {
    const seen = new Map();
    for (const t of tokens) {
      const name = nameOf(t.id);
      if (seen.has(name)) throw new Error(`tokens "${seen.get(name)}" and "${t.id}" both export as ${name}`);
      seen.set(name, t.id);
    }
  }
}

/**
 * Data for the Figma plugin (tools/figma-plugin/plugin.js). Keeps the layering and the aliases, so Figma
 * variables reference each other the same way tokens do. Collections mirror the token files:
 * primitive / base (one mode), theme (one mode per theme), platform (one mode per platform), component (one mode).
 */
function buildFigmaData(combos) {
  const all = loadSet(DEFAULT.theme, DEFAULT.platform);
  const typeOf = (id) => resolve(all, id).type;
  const entry = (t, values) => ({ id: t.id, type: typeOf(t.id), values, ...(t.description ? { description: t.description } : {}) });
  const single = (files, layer) => {
    const map = new Map();
    for (const file of files) flatten(readJson(file), layer, map);
    return { modes: ['value'], tokens: [...map.values()].map((t) => entry(t, { value: t.value })) };
  };
  const perMode = (modes, fileOf, layer) => {
    const maps = modes.map((m) => flatten(readJson(fileOf(m)), layer, new Map()));
    return {
      modes,
      tokens: [...maps[0].values()].map((t) => entry(t, Object.fromEntries(modes.map((m, i) => [m, maps[i].get(t.id).value])))),
    };
  };
  const componentFiles = readdirSync(tokensPath('component')).filter((f) => f.endsWith('.json')).sort().map((f) => tokensPath('component', f));
  const resolved = {};
  for (const [key, tokens] of Object.entries(combos)) {
    resolved[key] = Object.fromEntries(tokens.map((t) => [publicName(t.id), cssValue(t)]));
  }
  return {
    system: SYSTEM,
    defaults: DEFAULT,
    themes: THEMES,
    platforms: PLATFORMS,
    collections: {
      primitive: single([tokensPath('primitive.json')], 'primitive'),
      base: single([tokensPath('base.json')], 'semantic'),
      theme: perMode(THEMES, (t) => tokensPath('semantic', `${t}.json`), 'semantic'),
      platform: perMode(PLATFORMS, (p) => tokensPath('modes', `${p}.json`), 'semantic'),
      component: single(componentFiles, 'component'),
    },
    resolved,
  };
}

function buildFigmaPlugin(combos) {
  const source = readFileSync(join(ROOT, 'tools', 'figma-plugin', 'plugin.js'), 'utf8');
  const data = JSON.stringify(buildFigmaData(combos));
  write(buildPath('figma', 'code.js'), `/* ${GENERATED_NOTE} Plugin source: tools/figma-plugin/plugin.js */\nconst NN_DATA = ${data};\n\n${source}`);
  write(buildPath('figma', 'manifest.json'), readFileSync(join(ROOT, 'tools', 'figma-plugin', 'manifest.json'), 'utf8'));
}

function main() {
  assertSameNames('theme', THEMES, (t) => tokensPath('semantic', `${t}.json`));
  assertSameNames('platform mode', PLATFORMS, (p) => tokensPath('modes', `${p}.json`));
  const combos = {};
  for (const theme of THEMES) for (const platform of PLATFORMS) combos[`${theme}/${platform}`] = resolvedSet(theme, platform);
  assertUniqueOutputNames(combos[`${DEFAULT.theme}/${DEFAULT.platform}`]);

  const audit = THEMES.flatMap(runAudit);

  write(buildPath('web', 'tokens.css'), buildCss(combos));
  write(buildPath('web', 'tokens.js'), buildJs(combos, audit));
  for (const platform of EMBEDDED_PLATFORMS) {
    const suffix = suffixOf(platform);
    for (const theme of THEMES) {
      write(buildPath('embedded', headerName(theme, suffix)), buildHeader(theme, platform, combos[`${theme}/${platform}`]));
    }
  }
  write(buildPath('embedded', `${SYSTEM.file}_theme.h`), buildSelectorHeader());
  write(buildPath('audit.md'), buildAuditMd(audit));
  buildFigmaPlugin(combos);

  const count = combos[`${DEFAULT.theme}/${DEFAULT.platform}`].length;
  const failed = audit.filter((r) => !r.pass);
  console.log(`ok   ${count} tokens x ${THEMES.length} themes x ${PLATFORMS.length} platforms`);
  console.log('ok   build/web/tokens.css, build/web/tokens.js');
  console.log(`ok   build/embedded/${SYSTEM.file}_theme.h + ${EMBEDDED_PLATFORMS.length * THEMES.length} theme headers`);
  console.log('ok   build/figma/ (Figma plugin: import build/figma/manifest.json in Figma desktop)');
  console.log(`${failed.length ? 'WARN' : 'ok  '} contrast audit: ${audit.length - failed.length}/${audit.length} pass (build/audit.md)`);
  for (const r of failed) console.log(`     FAIL [${r.theme}] ${r.fg}${r.alpha ? ` @${r.alpha}` : ''} on ${r.bg}: ${r.ratio} < ${r.min}`);
  if (STRICT && failed.length) process.exit(1);
}

